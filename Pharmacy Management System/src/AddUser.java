    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
     String UserRole=(String)comboUserRole.getSelectedItem(); 
     String name =txtName.getText();
     SimpleDateFormat dFormat=new SimpleDateFormat("dd-MM-yyyy");
     Date date=dateDOB.getDate();// TODO add your handling code here:
      String dob = "";
     if (date != null) {
    dob = dFormat.format(date); // use 'date', not dateDOB.getDate()
}
     String mobileNumber=txtMobileNumber.getText();
     String email=txtEmail.getText();
     String username=txtUsername.getText();
     String password=txtPassword.getText();
     String address=txtAddress.getText();
     if(name.equals(""))
     {
         JOptionPane.showMessageDialog(null,"Name field is required");
     } else if(dob.equals(""))
     {
         JOptionPane.showMessageDialog(null,"Date of birth field is required");
     } else if( mobileNumber.equals(""))
     {
         JOptionPane.showMessageDialog(null,"Mobile Number field is required");
     } else if (!mobileNumber.startsWith("03") || mobileNumber.length() != 11) {
    JOptionPane.showMessageDialog(null, "Mobile Number field is invalid (should start with 03 and be 11 digits)");
} else if(email.equals(""))
     {
          JOptionPane.showMessageDialog(null,"Email field is required"); 
     }else if(!email.matches("[a-zA-Z0-9]+[@]+[a-zA-Z0-9]+[.]+[a-zA-Z0-9]+$"))
     {
         JOptionPane.showMessageDialog(null,"Email field is invalid"); 
     } else if(username.equals(""))
     {
         JOptionPane.showMessageDialog(null,"Username field is required"); 
     } else if(checkUsername==1){
         JOptionPane.showMessageDialog(null,"Username already exists");
     }else if(password.equals(""))
     {
         JOptionPane.showMessageDialog(null,"password field is required"); 
     } else if(address.equals(""))
     {
         JOptionPane.showMessageDialog(null," field is required"); 
     } else{
         try{
             Connection con=ConnectionProvider.getCon();
             PreparedStatement ps= con.prepareStatement("insert into appuser(UserRole,name,dob,mobileNumber,email,username,password,address)values(?,?,?,?,?,?,?,?)");
    
             ps.setString(1,UserRole);
             ps.setString(2,name);
             ps.setString(3,dob);
             ps.setString(4,mobileNumber);
             ps.setString(5,email);
             ps.setString(6,username);
             ps.setString(7,password);
             ps.setString(8,address);
             ps.executeUpdate();
             JOptionPane.showMessageDialog(null,"User added successfully");
             setVisible(false);
             new AddUser().setVisible(true);
             
         }
         catch(Exception e){
             JOptionPane.showMessageDialog(null,e);
         }
     }
     
    }//GEN-LAST:event_jButton1ActionPerformed

