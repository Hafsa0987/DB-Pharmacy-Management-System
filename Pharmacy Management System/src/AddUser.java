    private void txtUsernameKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtUsernameKeyReleased
    String username=txtUsername.getText();    
    if(!username.equals(""))
    {
        
           iconLabel.setVisible(true);// TODO add your handling code here:
           iconLabel.setIcon(new ImageIcon("src\\images\\yes.png"));
           iconLabel.setText("");
           checkUsername=0;
           try{
               Connection con= ConnectionProvider.getCon(); //Connects Java application with MySQL database.
               Statement st=con.createStatement();// create SQL statement object
               ResultSet rs=st.executeQuery("select *from appuser where username='" +username+"'"); //checks if username already exist in database
               while(rs.next())
               {
                   checkUsername=1;
                   iconLabel.setIcon(new ImageIcon("src\\images\\no.png")); //show red cross or no icon
                   iconLabel.setText("");
               }
           }
           catch(Exception e)
           {
               JOptionPane.showMessageDialog(null,e);
           }
    }
    else
    {
        iconLabel.setVisible(false);
    }
    }//GEN-LAST:event_txtUsernameKeyReleased
 
